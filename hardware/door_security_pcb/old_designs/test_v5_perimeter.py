crossings = 0
for s_v5 in v5_lcd:
    for kt in keypad_tracks:
        for s_k in kt:
            if intersect(s_v5[0], s_v5[1], s_k[0], s_k[1]):
                print("CROSSING:", s_v5, s_k)
                crossings += 1

print(f"Crossings between +5V LCD perimeter track and Keypad tracks: {crossings}")
